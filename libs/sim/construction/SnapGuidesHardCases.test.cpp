	// The prototype's long wall chain: point i at i * 37 degrees, 1 + 0.35 i meters from the origin.
	std::vector<Vec2> spiral(int count) {
		std::vector<Vec2> points;
		for (int index = 0; index < count; ++index) {
			const double angle = index * 37.0 * kRadiansPerDegree;
			const double radius = 1.0 + index * 0.35;
			points.push_back(meters(millimeters(std::cos(angle) * radius, std::sin(angle) * radius)));
		}
		return points;
	}
