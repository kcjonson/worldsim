// Fails when a test has fewer EXPECT_* / ASSERT_* assertions at head than at a base ref.
// Usage: node scripts/test-assertions.mjs [--base <ref>] [--json]
// Base defaults to the merge-base of HEAD and origin/main; head is the working tree (untracked files included).
// Covers every *.test.cpp. Tests are keyed Suite.Name from TEST, TEST_F and TEST_P, so a test moved or
// renamed-by-file still matches; counts for a key repeated across files are summed. Assertions outside any
// test body count under `<file>::helpers`, per file.
// Limits: parsing is textual (comments, string, char and raw-string literals are blanked, then braces are
// matched), with no preprocessor. A test written through an unknown macro, or generated by a macro, is
// seen as helper code. Assertions hidden behind a macro of your own are not counted. A helper moved to
// another file reads as a drop on the old file's key. Only the macro count is compared, not what it checks.

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';

const kTestFileSuffix = '.test.cpp';
const kTestMacro = /\b(?:TEST|TEST_F|TEST_P)\s*\(\s*(\w+)\s*,\s*(\w+)\s*\)\s*\{/g;
const kAssertionMacro = /\b(?:EXPECT|ASSERT)_\w+\s*\(/g;

function git(args) {
	return execFileSync('git', args, { encoding: 'utf8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'pipe'] });
}

function parseArgs(argv) {
	const options = { base: null, json: false };
	for (let index = 0; index < argv.length; index++) {
		if (argv[index] === '--json') options.json = true;
		else if (argv[index] === '--base' && index + 1 < argv.length) options.base = argv[++index];
		else throw new Error(`unknown argument: ${argv[index]}`);
	}
	return options;
}

function blankNonCode(source) {
	const out = source.split('');
	const length = source.length;
	const blank = (from, to) => {
		for (let at = from; at < to; at++) if (out[at] !== '\n') out[at] = ' ';
	};
	let at = 0;
	while (at < length) {
		const char = source[at];
		const next = source[at + 1];
		if (char === '/' && next === '/') {
			let end = at;
			while (end < length && source[end] !== '\n') end++;
			blank(at, end);
			at = end;
		} else if (char === '/' && next === '*') {
			const close = source.indexOf('*/', at + 2);
			const end = close === -1 ? length : close + 2;
			blank(at, end);
			at = end;
		} else if (char === '"') {
			const rawMatch = at > 0 && source[at - 1] === 'R' ? /^"([^()\\\s]{0,16})\(/.exec(source.slice(at, at + 20)) : null;
			if (rawMatch) {
				const terminator = `)${rawMatch[1]}"`;
				const close = source.indexOf(terminator, at + rawMatch[0].length);
				const end = close === -1 ? length : close + terminator.length;
				blank(at, end);
				at = end;
			} else {
				let end = at + 1;
				while (end < length && source[end] !== '"' && source[end] !== '\n') end += source[end] === '\\' ? 2 : 1;
				blank(at, end + 1);
				at = end + 1;
			}
		} else if (char === "'") {
			if (at > 0 && /[0-9A-Za-z]/.test(source[at - 1])) {
				at++;
				continue;
			}
			let end = at + 1;
			while (end < length && source[end] !== "'" && source[end] !== '\n') end += source[end] === '\\' ? 2 : 1;
			blank(at, end + 1);
			at = end + 1;
		} else {
			at++;
		}
	}
	return out.join('');
}

function matchingBrace(code, open) {
	let depth = 0;
	for (let at = open; at < code.length; at++) {
		if (code[at] === '{') depth++;
		else if (code[at] === '}' && --depth === 0) return at;
	}
	return code.length - 1;
}

function countAssertions(code) {
	return (code.match(kAssertionMacro) ?? []).length;
}

function countFile(path, source, counts) {
	const code = blankNonCode(source);
	const outside = code.split('');
	const add = (key, amount) => counts.set(key, (counts.get(key) ?? 0) + amount);
	kTestMacro.lastIndex = 0;
	let match;
	while ((match = kTestMacro.exec(code)) !== null) {
		const open = match.index + match[0].length - 1;
		const close = matchingBrace(code, open);
		add(`${match[1]}.${match[2]}`, countAssertions(code.slice(open, close + 1)));
		for (let at = match.index; at <= close; at++) if (outside[at] !== '\n') outside[at] = ' ';
		kTestMacro.lastIndex = close + 1;
	}
	const helpers = countAssertions(outside.join(''));
	if (helpers > 0) add(`${path}::helpers`, helpers);
}

function fileOfKey(files, key) {
	return files.get(key) ?? null;
}

function collect(paths, readSource) {
	const counts = new Map();
	const files = new Map();
	for (const path of paths) {
		const perFile = new Map();
		countFile(path, readSource(path), perFile);
		for (const [key, count] of perFile) {
			counts.set(key, (counts.get(key) ?? 0) + count);
			if (!files.has(key)) files.set(key, path);
		}
	}
	return { counts, files };
}

function main() {
	const options = parseArgs(process.argv.slice(2));
	const base = options.base ?? git(['merge-base', 'HEAD', 'origin/main']).trim();
	const baseFiles = git(['ls-tree', '-r', '--name-only', base]).split('\n').filter((path) => path.endsWith(kTestFileSuffix));
	const headFiles = git(['ls-files', '--cached', '--others', '--exclude-standard'])
		.split('\n')
		.filter((path) => path.endsWith(kTestFileSuffix) && existsSync(path));
	const baseResult = collect(baseFiles, (path) => git(['show', `${base}:${path}`]));
	const headResult = collect(headFiles, (path) => readFileSync(path, 'utf8'));

	const drops = [];
	for (const [key, baseCount] of baseResult.counts) {
		const headCount = headResult.counts.get(key) ?? 0;
		if (headCount < baseCount) {
			drops.push({
				test: key,
				file: fileOfKey(headResult.files, key) ?? fileOfKey(baseResult.files, key),
				baseFile: fileOfKey(baseResult.files, key),
				base: baseCount,
				head: headCount,
				vanished: !headResult.counts.has(key),
			});
		}
	}
	const summary = {
		base,
		baseTests: baseResult.counts.size,
		headTests: headResult.counts.size,
		baseAssertions: [...baseResult.counts.values()].reduce((sum, count) => sum + count, 0),
		headAssertions: [...headResult.counts.values()].reduce((sum, count) => sum + count, 0),
		drops: drops.length,
	};

	if (options.json) {
		console.log(JSON.stringify({ summary, drops }, null, 2));
	} else {
		for (const drop of drops) {
			const where = drop.vanished ? `${drop.baseFile} (gone at head)` : drop.file;
			console.log(`DROP ${drop.test} in ${where}: ${drop.base} -> ${drop.head}`);
		}
		console.log(
			`test-assertions: base ${base.slice(0, 10)}, ${summary.baseTests} keys / ${summary.baseAssertions} assertions -> ` +
				`${summary.headTests} keys / ${summary.headAssertions} assertions, ${drops.length} drop(s)`,
		);
	}
	process.exit(drops.length > 0 ? 1 : 0);
}

main();
