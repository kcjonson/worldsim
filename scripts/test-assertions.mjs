// Fails when a test has fewer assertion macros (EXPECT_*, ASSERT_*, FAIL, ADD_FAILURE, GTEST_FAIL) at head than at a base ref.
// Usage: node scripts/test-assertions.mjs [--base <ref>] [--json]   (any working directory inside the repo)
// Exit codes: 0 no drop, 1 at least one drop, 2 the parse cannot be trusted, bad arguments, or any error.
// With --json, stdout is always one JSON object; on exit 2 it is {"error": "..."} and the text is also on stderr.
// Base defaults to the merge-base of HEAD and origin/main; head is the working tree (untracked files included,
// staged-only changes are not what is compared). In a shallow clone with no origin/main the default base fails:
// pass --base or fetch fully. --base is for comparing against a specific earlier commit; passing origin/main on a
// branch that is behind main reports main's own edits as drops.
// Covers every *.test.cpp. Tests are keyed Suite.Name from TEST, TEST_F and TEST_P, so a test moved to another
// file still matches; counts for a key repeated across files are summed. A test generated by a macro of the
// project's own is keyed by the macro's parameter names as written (the TEST line inside the macro body).
// Tests defined inside a #define (continuation lines included) are not counted; the directive is blanked.
// Assertions outside any test body count under `<file>::helpers`, per file.
// On a drop, NEW lines (keys only at head) and RISE lines (keys whose count rose) show where assertions went;
// they never offset a drop. Output is sorted by file, then key.
// Self-check: a file whose braces do not balance, or whose keyed test count differs from a plain count of
// TEST/TEST_F/TEST_P openings, is reported and the run exits 2 rather than trusting the parse.
// Limits: parsing is textual (comments, string, char and raw-string literals are blanked, then braces are
// matched), with no preprocessor, so #if branches all count and line-continued comments are not understood.
// Assertions hidden behind a macro of your own are not counted. A helper moved to another file reads as a
// drop on the old file's key. Only the macro count is compared, not what any macro checks.

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const kTestFileSuffix = '.test.cpp';
const kTestMacro = /\b(?:TEST|TEST_F|TEST_P)\s*\(\s*(\w+)\s*,\s*(\w+)\s*\)\s*\{/g;
const kAssertionMacro = /\b(?:EXPECT_\w+|ASSERT_\w+|FAIL|ADD_FAILURE\w*|GTEST_FAIL\w*)\s*\(/g;
const kTestOpening = /\bTEST(?:_F|_P)?\s*\(/g;
const kRawPrefix = /^(?:u8|u|U|L)?R$/;
const kDefineDirective = /^[ \t]*#[ \t]*define\b(?:[^\n]*\\[ \t]*\n)*[^\n]*/gm;

let repoRoot = process.cwd();

class UsageError extends Error {}

function git(args) {
	return execFileSync('git', args, { cwd: repoRoot, encoding: 'utf8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'pipe'] });
}

function gitPaths(args) {
	return git(args).split('\0').filter((path) => path.endsWith(kTestFileSuffix));
}

function resolveCommit(ref) {
	try {
		return git(['rev-parse', '--verify', '--quiet', `${ref}^{commit}`]).trim();
	} catch {
		throw new UsageError(`not a commit: ${ref}`);
	}
}

function parseArgs(argv) {
	const options = { base: null, json: false };
	for (let index = 0; index < argv.length; index++) {
		if (argv[index] === '--json') options.json = true;
		else if (argv[index] === '--base') {
			const value = argv[++index];
			if (value === undefined || value.startsWith('-')) throw new UsageError('--base needs a ref');
			options.base = value;
		} else throw new UsageError(`unknown argument: ${argv[index]}`);
	}
	return options;
}

function tokenBefore(source, at) {
	let start = at;
	while (start > 0 && /[0-9A-Za-z_]/.test(source[start - 1])) start--;
	return source.slice(start, at);
}

function blankDirectives(code) {
	return code.replace(kDefineDirective, (directive) => directive.replace(/[^\n]/g, ' '));
}

function blankNonCode(source) {
	const out = source.split('');
	const length = source.length;
	const blank = (from, to) => {
		for (let at = from; at < to; at++) if (out[at] !== '\n') out[at] = ' ';
	};
	let at = 0;
	while (at < length) {
		const char = source[at];
		const next = source[at + 1];
		if (char === '/' && next === '/') {
			let end = at;
			while (end < length && source[end] !== '\n') end++;
			blank(at, end);
			at = end;
		} else if (char === '/' && next === '*') {
			const close = source.indexOf('*/', at + 2);
			const end = close === -1 ? length : close + 2;
			blank(at, end);
			at = end;
		} else if (char === '"') {
			const rawMatch = kRawPrefix.test(tokenBefore(source, at)) ? /^"([^()\\\s]{0,16})\(/.exec(source.slice(at, at + 20)) : null;
			if (rawMatch) {
				const terminator = `)${rawMatch[1]}"`;
				const close = source.indexOf(terminator, at + rawMatch[0].length);
				const end = close === -1 ? length : close + terminator.length;
				blank(at, end);
				at = end;
			} else {
				let end = at + 1;
				while (end < length && source[end] !== '"' && source[end] !== '\n') end += source[end] === '\\' ? 2 : 1;
				blank(at, end + 1);
				at = end + 1;
			}
		} else if (char === "'") {
			let start = at;
			while (start > 0 && /[0-9A-Za-z_']/.test(source[start - 1])) start--;
			if (start < at && /[0-9]/.test(source[start])) {
				at++;
				continue;
			}
			let end = at + 1;
			while (end < length && source[end] !== "'" && source[end] !== '\n') end += source[end] === '\\' ? 2 : 1;
			blank(at, end + 1);
			at = end + 1;
		} else {
			at++;
		}
	}
	return blankDirectives(out.join(''));
}

function matchingBrace(code, open) {
	let depth = 0;
	for (let at = open; at < code.length; at++) {
		if (code[at] === '{') depth++;
		else if (code[at] === '}' && --depth === 0) return at;
	}
	return -1;
}

function countAssertions(code) {
	return (code.match(kAssertionMacro) ?? []).length;
}

function countFile(path, source, counts, problems) {
	const code = blankNonCode(source);
	const outside = code.split('');
	const add = (key, amount) => counts.set(key, (counts.get(key) ?? 0) + amount);
	kTestMacro.lastIndex = 0;
	let match;
	let keyed = 0;
	while ((match = kTestMacro.exec(code)) !== null) {
		const open = match.index + match[0].length - 1;
		const close = matchingBrace(code, open);
		if (close === -1) {
			problems.push(`${path}: braces of ${match[1]}.${match[2]} do not balance`);
			break;
		}
		keyed++;
		add(`${match[1]}.${match[2]}`, countAssertions(code.slice(open, close + 1)));
		for (let at = match.index; at <= close; at++) if (outside[at] !== '\n') outside[at] = ' ';
		kTestMacro.lastIndex = close + 1;
	}
	const opened = (code.match(kTestOpening) ?? []).length;
	if (opened !== keyed && !problems.some((problem) => problem.startsWith(`${path}:`))) {
		problems.push(`${path}: ${opened} TEST openings but ${keyed} parsed tests`);
	}
	const helpers = countAssertions(outside.join(''));
	if (helpers > 0) add(`${path}::helpers`, helpers);
}

function collect(paths, readSource, problems) {
	const counts = new Map();
	const files = new Map();
	for (const path of paths) {
		const perFile = new Map();
		countFile(path, readSource(path), perFile, problems);
		for (const [key, count] of perFile) {
			counts.set(key, (counts.get(key) ?? 0) + count);
			if (!files.has(key)) files.set(key, path);
		}
	}
	return { counts, files };
}

function compare(baseResult, headResult) {
	const drops = [];
	const rises = [];
	const added = [];
	for (const [key, baseCount] of baseResult.counts) {
		const headCount = headResult.counts.get(key) ?? 0;
		if (headCount < baseCount) {
			drops.push({
				test: key,
				file: headResult.files.get(key) ?? baseResult.files.get(key),
				baseFile: baseResult.files.get(key),
				base: baseCount,
				head: headCount,
				vanished: !headResult.counts.has(key),
			});
		} else if (headCount > baseCount) {
			rises.push({ test: key, file: headResult.files.get(key), base: baseCount, head: headCount });
		}
	}
	for (const [key, headCount] of headResult.counts) {
		if (!baseResult.counts.has(key)) added.push({ test: key, file: headResult.files.get(key), head: headCount });
	}
	const displayFile = (entry) => (entry.vanished ? entry.baseFile : entry.file);
	const byFileThenKey = (left, right) => {
		const leftFile = displayFile(left);
		const rightFile = displayFile(right);
		if (leftFile !== rightFile) return leftFile < rightFile ? -1 : 1;
		return left.test < right.test ? -1 : left.test > right.test ? 1 : 0;
	};
	return { drops: drops.sort(byFileThenKey), rises: rises.sort(byFileThenKey), added: added.sort(byFileThenKey) };
}

function sumCounts(result) {
	return [...result.counts.values()].reduce((sum, count) => sum + count, 0);
}

function main() {
	const options = parseArgs(process.argv.slice(2));
	try {
		repoRoot = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
	} catch {
		throw new UsageError('not inside a git repository');
	}
	let base;
	if (options.base !== null) base = resolveCommit(options.base);
	else {
		try {
			base = git(['merge-base', 'HEAD', 'origin/main']).trim();
		} catch {
			throw new UsageError('no merge-base with origin/main; pass --base <ref>');
		}
	}
	const baseFiles = gitPaths(['ls-tree', '-r', '-z', '--name-only', base]);
	const headFiles = gitPaths(['ls-files', '-z', '--cached', '--others', '--exclude-standard']).filter((path) =>
		existsSync(join(repoRoot, path)),
	);
	const problems = [];
	const baseResult = collect(baseFiles, (path) => git(['show', `${base}:${path}`]), problems);
	const headResult = collect(headFiles, (path) => readFileSync(join(repoRoot, path), 'utf8'), problems);
	if (problems.length > 0) {
		for (const problem of problems) console.error(`PARSE ${problem}`);
		throw new UsageError(`parse cannot be trusted, failing (${problems.length} problem(s), first: ${problems[0]})`);
	}

	const { drops, rises, added } = compare(baseResult, headResult);
	const baseAssertions = sumCounts(baseResult);
	const headAssertions = sumCounts(headResult);
	const summary = {
		base,
		baseTests: baseResult.counts.size,
		headTests: headResult.counts.size,
		baseAssertions,
		headAssertions,
		netAssertions: headAssertions - baseAssertions,
		drops: drops.length,
	};

	if (options.json) {
		console.log(JSON.stringify({ summary, drops, added, rises }, null, 2));
	} else {
		for (const drop of drops) {
			const where = drop.vanished ? `${drop.baseFile} (gone at head)` : drop.file;
			console.log(`DROP ${drop.test} in ${where}: ${drop.base} -> ${drop.head}`);
		}
		if (drops.length > 0) {
			for (const entry of added) console.log(`NEW ${entry.test} in ${entry.file}: ${entry.head}`);
			for (const rise of rises) console.log(`RISE ${rise.test} in ${rise.file}: ${rise.base} -> ${rise.head}`);
		}
		const net = summary.netAssertions > 0 ? `+${summary.netAssertions}` : String(summary.netAssertions);
		console.log(
			`test-assertions: base ${base.slice(0, 10)}, ${summary.baseTests} keys / ${baseAssertions} assertions -> ` +
				`${summary.headTests} keys / ${headAssertions} assertions (net ${net}), ${drops.length} drop(s)`,
		);
	}
	process.exit(drops.length > 0 ? 1 : 0);
}

function failUntrusted(message) {
	const line = message.replace(/\s+/g, ' ').trim();
	console.error(`test-assertions: ${line}`);
	if (process.argv.includes('--json')) console.log(JSON.stringify({ error: line }));
	process.exit(2);
}

try {
	main();
} catch (error) {
	failUntrusted(error instanceof Error ? error.message : String(error));
}
